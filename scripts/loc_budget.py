# ---------------------------------------------------------------- 字句解析
#
# 1 文字ずつ走査する状態機械。外部ライブラリは使わない (正規表現は前置きの識別だけ)。


@dataclass(frozen=True)
class Token:
    text: str    # 識別子 / 数値 / 記号 / "<lit>" (文字列・char) / "<lifetime>"
    line: int    # 0-based


@dataclass
class Lexed:
    rel: str
    lines: list[str]
    kind: list[str]            # 'code' | 'doc' | 'comment' | 'blank' (テスト判定前)
    indent: list[int | None]   # code 行のうち「行頭が literal/comment の継続でない」行だけ段数
    tokens: list[Token]


# raw string の前置き。`br` `rb` `cr` `rc` `r` + `#`*n + `"`。**識別子より先に試す**。
_RAWSTR_RE = re.compile(r'(?:br|rb|cr|rc|r)(#*)"')
# byte string / C string。`b"` `c"`。
_BYTESTR_RE = re.compile(r'[bc]"')
# 生の識別子 `r#type`。raw string と紛らわしいので明示的に扱う。
_RAWIDENT_RE = re.compile(r"r#(?![\"#])[A-Za-z_][A-Za-z0-9_]*")

# 多文字記号。**`->` を 1 トークンにするのは必須** — 1 文字ずつに割ると
# `fn f() -> bool {` の `>` が angle 深さを 1 減らし、本体の開き `{` を取り違える。
_SYM3 = ("..=",)
_SYM2 = ("->", "=>", "::", "..", "<<", ">>", "<=", ">=", "==", "!=", "&&")


def _split_lines(src: str) -> list[str]:
    """物理行へ割る。**universal newlines を使わない** (単独 CR まで改行に化けて
    `wc -l` と食い違う)。末尾が改行で終わっていたら最後の空要素を 1 つだけ落とす。
    CRLF のファイルが 28 本あるので、各行の末尾 `\\r` を 1 つだけ落とす。"""
    if src == "":
        return []
    parts = src.split("\n")
    if src.endswith("\n"):
        parts.pop()
    return [p[:-1] if p.endswith("\r") else p for p in parts]


def _indent_steps(line: str) -> int:
    """行頭の空白を tab=4 で展開し、4 で割った商 = インデント段数。**絶対値**で測る
    (mod / impl のラッパも段数に数える)。r.md #77 が使っている指標と揃えるため。"""
    col = 0
    for ch in line:
        if ch == " ":
            col += 1
        elif ch == "\t":
            col = (col // INDENT_WIDTH + 1) * INDENT_WIDTH
        else:
            break
    return col // INDENT_WIDTH


def _is_ident(text: str) -> bool:
    """**lex() が識別子として切り出す規則と同一にする。** ASCII 限定の正規表現にすると
    Rust が許す非 ASCII 識別子 (`fn 日本語名()`) で `fn` の次が識別子と見なされず、
    その関数が **黙って計測から落ちる** (= 違反が消える方向の故障)。
    `<lit>` / `<lifetime>` は `<` で始まるのでここには当たらない。"""
    if not text:
        return False
    if not (text[0].isalpha() or text[0] == "_"):
        return False
    return all(ch.isalnum() or ch == "_" for ch in text[1:])


def lex(src: str, rel: str = "<mem>") -> Lexed:
    """Rust の字句解析。行分類 (code / doc / comment / blank) とトークン列を返す。

    行分類は相互排他で、この順に決める:
        code    … コメントに属さない非空白文字が 1 つ以上ある行 (文字列の中身を含む)
        doc     … code でなく、doc comment の非空白文字がある行
        comment … code でも doc でもなく、通常コメントの非空白文字がある行
        blank   … 上のいずれでもない
    """
    lines = _split_lines(src)
    text = "\n".join(lines)
    n = len(text)
    nlines = len(lines)
    f_code = [False] * nlines
    f_doc = [False] * nlines
    f_comment = [False] * nlines
    # carry[i] = 行 i の最初の非空白文字が、前の行から続く文字列リテラル /
    # ブロックコメントの内側にある。これを見ないと common/src/video_fx.rs の WGSL の
    # 字下げが関数のネスト段数に化ける。
    carry = [False] * nlines
    tokens: list[Token] = []
    i = 0
    line = 0

    def consume(start: int, end: int, bucket: list[bool], cont: bool) -> None:
        """[start, end) を bucket に記録して現在行を進める。cont=True なら
        またいだ先の行を「継続行」として記録する (文字列リテラル / ブロックコメント)。"""
        nonlocal line
        seg = text[start:end]
        if "\n" not in seg:
            if seg.strip():
                bucket[line] = True
            return
        parts = seg.split("\n")
        for k, p in enumerate(parts):
            if p.strip() and line + k < nlines:
                bucket[line + k] = True
        if cont:
            for k in range(1, len(parts)):
                if line + k < nlines:
                    carry[line + k] = True
        line += len(parts) - 1

    while i < n:
        ch = text[i]
        if ch in " \t\r":
            i += 1
            continue
        if ch == "\n":
            line += 1
            i += 1
            continue

        # --- 行コメント。3 文字目が `/` または `!` かつ `////` でないなら doc。
        if ch == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            if j < 0:
                j = n
            head3 = text[i:i + 3]
            head4 = text[i:i + 4]
            is_doc = (head3 == "///" and head4 != "////") or head3 == "//!"
            consume(i, j, f_doc if is_doc else f_comment, False)
            i = j
            continue

        # --- ブロックコメント。**ネストを数える** (`/* /* */ */` が 1 個)。
        if ch == "/" and i + 1 < n and text[i + 1] == "*":
            head3 = text[i:i + 3]
            head4 = text[i:i + 4]
            is_doc = (head3 == "/**" and head4 != "/**/") or head3 == "/*!"
            depth = 0
            j = i
            while j < n:
                if text[j:j + 2] == "/*":
                    depth += 1
                    j += 2
                    continue
                if text[j:j + 2] == "*/":
                    depth -= 1
                    j += 2
                    if depth == 0:
                        break
                    continue
                j += 1
            j = min(j, n)
            consume(i, j, f_doc if is_doc else f_comment, True)
            i = j
            continue

        # --- raw string (中の `//` `/*` `{` `}` は一切解釈しない)
        m = _RAWSTR_RE.match(text, i)
        if m:
            closer = '"' + m.group(1)
            j = text.find(closer, m.end())
            j = n if j < 0 else j + len(closer)
            tokens.append(Token("<lit>", line))
            consume(i, j, f_code, True)
            i = j
            continue

        # --- 生の識別子 r#type (raw string と紛らわしいので raw string の後に試す)
        m = _RAWIDENT_RE.match(text, i)
        if m:
            tokens.append(Token(m.group(0)[2:], line))
            consume(i, m.end(), f_code, False)
            i = m.end()
            continue

        # --- 文字列 / byte string / C string
        quote_at = -1
        if ch == '"':
            quote_at = i
        elif _BYTESTR_RE.match(text, i):
            quote_at = i + 1
        if quote_at >= 0:
            j = quote_at + 1
            while j < n:
                c = text[j]
                if c == "\\":
                    j += 2
                    continue
                if c == '"':
                    j += 1
                    break
                j += 1
            tokens.append(Token("<lit>", line))
            consume(i, min(j, n), f_code, True)
            i = min(j, n)
            continue

        # --- char リテラル / ライフタイム。`'ident` は閉じ `'` を持たない。
        #     判別: 直後が `\` (エスケープ) か、2 つ先が `'` なら char。それ以外は
        #     ライフタイム。`'_'` は char、`'_` はライフタイムでどちらも正しく割れる。
        if ch == "'" or (ch == "b" and i + 1 < n and text[i + 1] == "'"):
            start = i
            q = i if ch == "'" else i + 1
            is_char = (q + 1 < n and text[q + 1] == "\\") or (q + 2 < n and text[q + 2] == "'")
            if is_char:
                # `\` は **次の 1 文字ごと飛ばす**。`'\\'` を「エスケープ開始が 2 つ」と
                # 読むと閉じ `'` を食い潰し、そこから先の字句解析が丸ごとずれる
                # (ui/crates/ui/src/shortcut.rs:500 の `('\\', ...)` で実際に起きた)。
                j = q + 1
                while j < n:
                    if text[j] == "\\":
                        j += 2
                        continue
                    if text[j] == "'":
                        j += 1
                        break
                    if text[j] == "\n":
                        break
                    j += 1
                j = min(j, n)
                tokens.append(Token("<lit>", line))
                consume(start, j, f_code, False)
                i = j
                continue
            if ch == "b":
                # b' で始まったのに char として閉じない = 実質ありえない。1 文字進めて逃げる。
                tokens.append(Token("b", line))
                consume(start, start + 1, f_code, False)
                i = start + 1
                continue
            j = i + 1
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            tokens.append(Token("<lifetime>", line))
            consume(i, j, f_code, False)
            i = j
            continue

        # --- 識別子 (unicode 識別子も許す)
        if ch.isalpha() or ch == "_":
            j = i + 1
            while j < n and (text[j].isalnum() or text[j] == "_"):
                j += 1
            tokens.append(Token(text[i:j], line))
            consume(i, j, f_code, False)
            i = j
            continue

        # --- 数値。`.` は直後が数字のときだけ取り込む (`1..2` を壊さない)。
        if ch.isdigit():
            j = i + 1
            while j < n:
                c = text[j]
                if c.isalnum() or c == "_":
                    j += 1
                elif c == "." and j + 1 < n and text[j + 1].isdigit():
                    j += 2
                else:
                    break
            tokens.append(Token(text[i:j], line))
            consume(i, j, f_code, False)
            i = j
            continue

        # --- 記号 (多文字を優先)
        sym = ""
        if text[i:i + 3] in _SYM3:
            sym = text[i:i + 3]
        elif text[i:i + 2] in _SYM2:
            sym = text[i:i + 2]
        else:
            sym = ch
        tokens.append(Token(sym, line))
        consume(i, i + len(sym), f_code, False)
        i += len(sym)

    kind: list[str] = []
    for k in range(nlines):
        if f_code[k]:
            kind.append("code")
        elif f_doc[k]:
            kind.append("doc")
        elif f_comment[k]:
            kind.append("comment")
        else:
            kind.append("blank")

    indent: list[int | None] = []
    for k in range(nlines):
        if kind[k] == "code" and not carry[k]:
            indent.append(_indent_steps(lines[k]))
        else:
            indent.append(None)

    return Lexed(rel=rel, lines=lines, kind=kind, indent=indent, tokens=tokens)


# ---------------------------------------------------------------- 属性


def _parse_attr(tokens: list[Token], i: int) -> tuple[str, str, int] | None:
    """tokens[i] が `#` のとき属性を読む。戻り値は (raw 連結, <lit> を空にした連結, 次の位置)。

    `<lit>` を空にした版を持つのは `#[cfg(feature = "test")]` を cfg(test) と
    誤検出しないため。キーに載せる版 (raw) では `<lit>` をそのまま残す。"""
    n = len(tokens)
    j = i + 1
    if j < n and tokens[j].text == "!":
        j += 1
    if j >= n or tokens[j].text != "[":
        return None
    depth = 1
    k = j + 1
    parts: list[str] = []
    while k < n:
        t = tokens[k].text
        if t == "[":
            depth += 1
        elif t == "]":
            depth -= 1
            if depth == 0:
                raw = "".join(parts)
                nolit = "".join("" if p == "<lit>" else p for p in parts)
                return raw, nolit, k + 1
        parts.append(t)
        k += 1
    return None


_CFG_TEST_RE = re.compile(r"(?<![A-Za-z0-9_])test(?![A-Za-z0-9_])")


def _strip_not_groups(text: str) -> str:
    """`not(…)` の部分木を丸ごと落とす。**`cfg(not(test))` を「テスト」と読まないため。**

    `not(test)` は「テストビルド **以外**でだけコンパイルされる」= production コードなので、
    テスト扱いにすると **production が丸ごと budget から消えて緑になる** (このリポジトリが
    最も警戒する false green)。素朴に `test` の語を探すだけだと
    `cfg(not(test))` / `cfg(all(not(test), windows))` が全部テスト扱いになる。
    `not(…)` を先に落としてから語を探せば、`cfg(all(test, not(windows)))` は
    テストのまま拾える。"""
    out: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        if text.startswith("not(", i):
            depth = 0
            k = i + 3            # `(` の位置
            while k < n:
                if text[k] == "(":
                    depth += 1
                elif text[k] == ")":
                    depth -= 1
                    if depth == 0:
                        break
                k += 1
            i = k + 1
            continue
        out.append(text[i])
        i += 1
    return "".join(out)


def _is_cfg_test(nolit: str) -> bool:
    """`cfg(all(test, windows))` / `cfg(any(test, …))` は意図的に拾う。
    **`cfg(not(test))` 系は拾わない** (production 専用コードなので。`_strip_not_groups`)。"""
    if not nolit.startswith("cfg("):
        return False
    return bool(_CFG_TEST_RE.search(_strip_not_groups(nolit)))


def _cfg_suffix(pending: list[tuple[str, int]]) -> str:
    """item に付いた `#[cfg(…)]` を正規化してキーの接尾辞にする。
    cfg 以外の属性 (`#[allow(...)]` / `#[derive(...)]` / doc 属性) はキーに入れない。"""
    cfgs = [c for c, _ in pending if c.startswith("cfg(")]
    return "[" + ",".join(cfgs) + "]" if cfgs else ""


# ---------------------------------------------------------------- cfg(test) 範囲


def _item_end_line(tokens: list[Token], j: int) -> int:
    """item の終端行。深さ 0 から始め、`(` `[` `{` で +1、`)` `]` `}` で −1。

    **−1 した結果が 0 になった `}` がその item の終端**。減算「前」の深さを見る実装に
    すると `mod tests { … }` は深さ 1 のまま `}` を見送ってファイル末尾まで走り、
    production コードが丸ごとテスト扱いになって budget が空振りする。

    **item ではないもの (struct の field / enum の variant / match の arm) に
    `#[cfg(test)]` が付いた場合の暴走を必ず止める**。それらは `;` でも `}` でも終わらないので、
    上の 2 規則だけだとファイル末尾まで走り、**残り全部がテスト扱い = 違反が黙って消える**。
    止め方は 2 つ:
      - 深さ 0 の `,` (囲みの `<…>` の中は数えない。`fn f<A, B>()` を切らないため)
      - 深さが負になる `)` `]` `}` = 囲みブロックの終わり。そこで打ち切る"""
    n = len(tokens)
    depth = 0
    angle = 0
    k = j
    while k < n:
        t = tokens[k].text
        if t in ("(", "[", "{"):
            depth += 1
        elif t in (")", "]", "}"):
            depth -= 1
            if depth == 0 and t == "}":
                if k + 1 < n and tokens[k + 1].text == ";":
                    return tokens[k + 1].line
                return tokens[k].line
            if depth < 0:
                # 囲みブロックの終わり。item ではないものに付いていた = ここで打ち切る。
                return tokens[k].line
        elif t == ";" and depth == 0:
            return tokens[k].line
        elif t == "," and depth == 0 and angle == 0:
            return tokens[k].line
        elif t == "<" and depth == 0:
            prev = tokens[k - 1].text if k > 0 else ""
            if _is_ident(prev) or prev in ("::", ">"):
                angle += 1
        elif t == ">" and depth == 0:
            angle = max(0, angle - 1)
        elif t == ">>" and depth == 0:
            angle = max(0, angle - 2)
        k += 1
    return tokens[n - 1].line if n else 0


def _mod_decl(tokens: list[Token], j: int) -> tuple[str, int] | None:
    """item が `[pub[(…)]] mod NAME ;` の形なら (NAME, 宣言行) を返す。"""
    n = len(tokens)
    k = j
    if k < n and tokens[k].text == "pub":
        k += 1
        if k < n and tokens[k].text == "(":
            depth = 1
            k += 1
            while k < n and depth > 0:
                if tokens[k].text == "(":
                    depth += 1
                elif tokens[k].text == ")":
                    depth -= 1
                k += 1
    if k + 2 >= n or tokens[k].text != "mod":
        return None
    if not _is_ident(tokens[k + 1].text):
        return None
    if tokens[k + 2].text != ";":
        return None
    return tokens[k + 1].text, tokens[k].line


def cfg_test_items(lx: Lexed) -> tuple[list[tuple[int, int]], list[tuple[str, int]]]:
    """`#[cfg(test)]` が付いた **あらゆる item** の範囲と、`#[cfg(test)] mod X;` の宣言を返す。

    範囲は「その item の最初の属性行の `#` がある行」から「item の終端行」まで。
    属性より上にある doc comment は範囲外 = doc として数える。だから **属性は 1 個ずつでは
    なく「連続した属性の塊」として読む** — `#[allow(x)]` が `#[cfg(test)]` の上にあるとき、
    範囲は `#[allow(x)]` の行から始まる。

    内部属性 (`#![…]`) は囲んでいる module に掛かるもので「次の item」には掛からないので、
    塊に含めない (拾うと後続の item の範囲が前へ伸びる)。"""
    tokens = lx.tokens
    n = len(tokens)
    ranges: list[tuple[int, int]] = []
    mod_decls: list[tuple[str, int]] = []
    i = 0
    while i < n:
        if tokens[i].text != "#":
            i += 1
            continue
        if i + 1 < n and tokens[i + 1].text == "!":
            # 内部属性。塊の開始にしない (読み飛ばすだけ)。
            parsed = _parse_attr(tokens, i)
            i = parsed[2] if parsed is not None else i + 1
            continue
        parsed = _parse_attr(tokens, i)
        if parsed is None:
            i += 1
            continue
        run_start_line = tokens[i].line
        is_test = _is_cfg_test(parsed[1])
        j = parsed[2]
        while j < n and tokens[j].text == "#":
            if j + 1 < n and tokens[j + 1].text == "!":
                break
            p2 = _parse_attr(tokens, j)
            if p2 is None:
                break
            is_test = is_test or _is_cfg_test(p2[1])
            j = p2[2]
        if is_test:
            ranges.append((run_start_line, _item_end_line(tokens, j)))
            md = _mod_decl(tokens, j)
            if md is not None:
                mod_decls.append(md)
        # 入れ子の `#[cfg(test)]` も拾えるよう、走査は item 本体の先頭から続ける
        i = j
    return ranges, mod_decls


# ---------------------------------------------------------------- 関数 item


def _brace_pairs(tokens: list[Token]) -> dict[int, int]:
    """`{` のトークン位置 → 対応する `}` のトークン位置。1 パスで作る
    (関数ごとに前方走査すると O(n^2) になる)。"""
    pairs: dict[int, int] = {}
    stack: list[int] = []
    for k, t in enumerate(tokens):
        if t.text == "{":
            stack.append(k)
        elif t.text == "}":
            if stack:
                pairs[stack.pop()] = k
    return pairs


def _find_body_open(tokens: list[Token], start: int) -> tuple[int, bool]:
    """paren / bracket / angle の 3 深さがすべて 0 のときに現れた最初の `{` を返す。

    `;` に当たったら本体無し (trait / extern の宣言)。bracket を数えるので
    `fn f<const N: usize>() -> [u8; { N * 2 }]` の `{` を本体と誤認しない。
    angle を数えるので `Foo<{ N }>` も巻き込まない。"""
    n = len(tokens)
    paren = bracket = angle = 0
    j = start
    while j < n:
        t = tokens[j].text
        if t == "{":
            if paren == 0 and bracket == 0 and angle == 0:
                return j, True
        elif t == ";":
            if paren == 0 and bracket == 0 and angle == 0:
                return j, False
        if t == "(":
            paren += 1
        elif t == ")":
            paren = max(0, paren - 1)
        elif t == "[":
            bracket += 1
        elif t == "]":
            bracket = max(0, bracket - 1)
        elif t == "<":
            prev = tokens[j - 1].text if j > 0 else ""
            if _is_ident(prev) or prev in ("::", ">"):
                angle += 1
        elif t == ">":
            angle = max(0, angle - 1)
        elif t == ">>":
            angle = max(0, angle - 2)
        j += 1
    return -1, False


def _skip_generics(tokens: list[Token], j: int) -> int:
    """tokens[j] が `<` ならその対応する `>` の次の位置を返す。そうでなければ j。"""
    n = len(tokens)
    if j >= n or tokens[j].text != "<":
        return j
    depth = 1
    j += 1
    while j < n and depth > 0:
        t = tokens[j].text
        if t == "<":
            depth += 1
        elif t == ">":
            depth -= 1
        elif t == ">>":
            depth -= 2
        j += 1
    return j


_SKIP_TYPE_WORDS = {"dyn", "mut", "impl"}


def _first_ident(tokens: list[Token], start: int, stop: int) -> str:
    for j in range(start, min(stop, len(tokens))):
        t = tokens[j].text
        if _is_ident(t) and t not in _SKIP_TYPE_WORDS:
            return t
    return "?"


# 属性と item キーワードの間に挟まってよいトークン。ここに無いものが現れたら
# pending 属性を捨てる (無関係な item の cfg が後続の fn のキーへ漏れるのを防ぐ)。
_TRANSPARENT = {"(", ")", "::", "<lit>"}

# `impl` の直前がこれらなら **型位置の `impl Trait`** (引数 / 戻り値 / 型引数) であって
# item の `impl` ブロックではない。区別しないと `fn f(x: impl Foo) { … }` の
# `impl` が「その関数自身の本体 `{`」を impl の本体と誤認し、関数の中に `Foo` という
# 偽のスコープが立って、入れ子の fn のキーが `<rel>::Foo::inner` に化ける。
_IMPL_TYPE_POS = {":", "->", "<", "(", "[", ",", "&", "+", "=", "|", "dyn", "as"}


def fn_items(lx: Lexed) -> list[tuple[str, int, int, int, int]]:
    """(qualified_key, attr_line, decl_line, body_open_line, body_close_line) を返す。
    すべて 0-based。key は `<rel>::<Scope>::<name>` (スコープが空なら `<rel>::<name>`)。

    **attr_line を返すのは必須** — 行内マーカーは「最初の属性行から本体の開き行まで」を
    探すので、宣言行から後方走査すると doc comment をどこまで遡るかが曖昧になり、
    上にある無関係な関数のマーカーを拾い得る。"""
    tokens = lx.tokens
    n = len(tokens)
    pairs = _brace_pairs(tokens)
    scope_open: dict[int, str] = {}      # 本体の開き `{` のトークン位置 → スコープ名
    scopes: list[tuple[str, int]] = []   # (名前, push 時点の brace 深さ)
    pending: list[tuple[str, int]] = []  # (属性の raw 連結, `#` の行)
    out: list[tuple[str, int, int, int, int]] = []
    depth = 0
    i = 0
    while i < n:
        t = tokens[i].text

        if t == "#":
            parsed = _parse_attr(tokens, i)
            if parsed is not None:
                # 内部属性 (`#![…]`) は囲む module に掛かるので、次の item には積まない
                # (積むと attr_line と cfg 接尾辞が無関係な fn へ漏れる)。
                if not (i + 1 < n and tokens[i + 1].text == "!"):
                    pending.append((parsed[0], tokens[i].line))
                i = parsed[2]
                continue

        if t == "{":
            if i in scope_open:
                scopes.append((scope_open[i], depth))
            depth += 1
            pending = []
            i += 1
            continue

        if t == "}":
            depth -= 1
            while scopes and scopes[-1][1] >= depth:
                scopes.pop()
            pending = []
            i += 1
            continue

        if t == "mod" and i + 1 < n and _is_ident(tokens[i + 1].text):
            if i + 2 < n and tokens[i + 2].text == "{":
                scope_open[i + 2] = tokens[i + 1].text + _cfg_suffix(pending)
            pending = []
            i += 1
            continue

        if t == "trait" and i + 1 < n and _is_ident(tokens[i + 1].text):
            body, has = _find_body_open(tokens, i + 2)
            if has:
                scope_open[body] = tokens[i + 1].text + _cfg_suffix(pending)
            pending = []
            i += 1
            continue

        if t == "impl":
            prev = tokens[i - 1].text if i > 0 else ""
            if prev in _IMPL_TYPE_POS:
                # 型位置の `impl Trait`。item ではないので scope を作らない。
                i += 1
                continue
            type_start = _skip_generics(tokens, i + 1)
            body, has = _find_body_open(tokens, type_start)
            if has:
                # paren / bracket / angle がすべて 0 の位置に `for` があれば trait impl。
                paren = bracket = angle = 0
                for_pos = -1
                for j in range(type_start, body):
                    tt = tokens[j].text
                    if tt == "for" and paren == 0 and bracket == 0 and angle == 0:
                        for_pos = j
                        break
                    if tt == "(":
                        paren += 1
                    elif tt == ")":
                        paren = max(0, paren - 1)
                    elif tt == "[":
                        bracket += 1
                    elif tt == "]":
                        bracket = max(0, bracket - 1)
                    elif tt == "<":
                        prev = tokens[j - 1].text if j > 0 else ""
                        if _is_ident(prev) or prev in ("::", ">"):
                            angle += 1
                    elif tt == ">":
                        angle = max(0, angle - 1)
                    elif tt == ">>":
                        angle = max(0, angle - 2)
                if for_pos >= 0:
                    trait_name = "".join(tk.text for tk in tokens[type_start:for_pos])
                    type_name = _first_ident(tokens, for_pos + 1, body)
                    scope_open[body] = f"{type_name}[{trait_name}]" + _cfg_suffix(pending)
                else:
                    type_name = _first_ident(tokens, type_start, body)
                    scope_open[body] = type_name + _cfg_suffix(pending)
            pending = []
            i += 1
            continue

        # 関数 item の判定: トークン `fn` の次が識別子 (関数ポインタ型 `fn(u32) -> u32` を除外)
        if t == "fn" and i + 1 < n and _is_ident(tokens[i + 1].text):
            name = tokens[i + 1].text + _cfg_suffix(pending)
            attr_line = pending[0][1] if pending else tokens[i].line
            decl_line = tokens[i].line
            body, has = _find_body_open(tokens, i + 2)
            if has:
                close = pairs.get(body, -1)
                if close >= 0:
                    scope = "::".join(s for s, _ in scopes)
                    key = f"{lx.rel}::{scope}::{name}" if scope else f"{lx.rel}::{name}"
                    out.append((key, attr_line, decl_line,
                                tokens[body].line, tokens[close].line))
            pending = []
            i += 1
            continue

        if not (_is_ident(t) or t in _TRANSPARENT):
            pending = []
        i += 1
    return out


# ---------------------------------------------------------------- 走査対象


def scan_files(argv: list[str] | None = None) -> list[str]:
    """走査対象を **原理で決める**: git が知っている `.rs` すべて。

    `--others --exclude-standard` を必ず付ける。`git ls-files` だけだと `git add` 前の
    新規巨大ファイルを見逃す = 検査器が黙って空振りする経路を新設してしまう。
    (`--exclude-standard` があるので `target/` や `third_party/` は .gitignore で落ちる。)

    **git が失敗したら空リストへ縮退させず例外**にする。空リストは「違反 0 + 完走マーカー
    あり」= 緑になり、しかも baseline 全行が「解消」として削除を案内される。"""
    cmd = argv or ["git", "ls-files", "-z", "--cached", "--others",
                   "--exclude-standard", "--", "*.rs"]
    try:
        proc = subprocess.run(cmd, cwd=ROOT, capture_output=True)
    except OSError as exc:
        raise LocBudgetError(f"git を起動できません ({cmd[0]}): {exc}") from exc
    if proc.returncode != 0:
        detail = proc.stderr.decode("utf-8", "replace").strip().splitlines()
        raise LocBudgetError(
            f"`{' '.join(cmd)}` が exit {proc.returncode} で失敗しました: "
            f"{detail[-1] if detail else '(詳細なし)'}"
        )
    out = proc.stdout.decode("utf-8", "replace")
    return [p for p in out.split("\0") if p]


def is_generated(lx: Lexed) -> bool:
    """ファイル先頭の連続するコメント / 空行ブロックの中に生成マーカーがあるか。
    **最初に `code` 行が現れた時点で打ち切る** — 行数窓にすると
    ara-sys/build.rs:47 の `.raw_line("// @generated …")` に届いて build.rs が落ちる。"""
    for k, kind in enumerate(lx.kind):
        if kind == "code":
            return False
        if kind in ("comment", "doc"):
            low = lx.lines[k].lower()
            if any(mark in low for mark in GEN_MARKERS):
                return True
    return False


def is_integration_test(rel: str) -> bool:
    """`tests/` `benches/` 直下の統合テスト。Rust の統合テストは crate 全体がテスト
    ビルド専用なので `#[cfg(test)]` を書かない = 属性経路にも mod 経路にも当たらない。
    判定は「パス成分に tests / benches があり、その親ディレクトリに Cargo.toml がある」
    = Cargo の規約そのもの。"""
    parts = rel.split("/")
    for k, p in enumerate(parts[:-1]):
        if p not in ("tests", "benches"):
            continue
        parent = "/".join(parts[:k])
        manifest = (ROOT / parent / "Cargo.toml") if parent else (ROOT / "Cargo.toml")
        if manifest.is_file():
            return True
    return False


def submodule_candidates(rel: str, name: str) -> list[str]:
    """`mod NAME;` の解決先候補。repo に `#[path = "…"] mod` は 1 件も無いので
    Rust の既定規則だけで足りる。将来 `#[path]` が入ったら解決に失敗するので、
    黙って外さず `UNRESOLVED-MOD` として表に出す。"""
    p = Path(rel)
    parent = p.parent.as_posix()
    parent = "" if parent == "." else parent + "/"
    if p.stem in ("mod", "lib", "main"):
        base = parent
    else:
        base = f"{parent}{p.stem}/"
    return [f"{base}{name}.rs", f"{base}{name}/mod.rs"]


