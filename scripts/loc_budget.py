@dataclass
class FileMetrics:
    rel: str
    raw: int          # 物理行
    ncloc: int        # 実コード行
    doc: int
    comment: int
    blank: int
    test: int         # テスト範囲に入る行 (種別を問わず)


@dataclass
class FnMetrics:
    key: str          # "<rel>::<Scope>::<name>" (スコープが空なら "<rel>::<name>")
    rel: str
    line: int         # 1-based。fn の宣言行
    attr_line: int    # 1-based。その fn の最初の属性行。無ければ line と同値
    body_open: int    # 1-based。本体の開き `{` の行。行内マーカーの探索範囲の下端
    ncloc: int
    max_indent: int
    deep_lines: int   # indent >= FN_INDENT_BUDGET の行数。ratchet の第 2 成分


@dataclass
class FileScan:
    metrics: FileMetrics
    fns: list[FnMetrics]
    lines: list[str]
    generated: bool
    force_test: bool
    test_mods: list[str] = field(default_factory=list)      # 解決できた `mod X;` の rel
    unresolved: list[tuple[int, str]] = field(default_factory=list)  # (1-based 行, 行内容)

    @property
    def rel(self) -> str:
        return self.metrics.rel


def _has_allow(lines: list[str], lo: int, hi: int, marker: str) -> bool:
    for k in range(max(0, lo), min(hi + 1, len(lines))):
        if marker in lines[k]:
            return True
    return False


def measure_source(rel: str, src: str, force_test: bool = False) -> FileScan:
    """**--check と --self-test が同じ経路を通るための分岐点**。合成フィクスチャも
    リポジトリのファイルも、必ずこの関数を通す。別実装で self-test を書くと
    「canary が検査対象と別物を試す」(scripts/arch_lint.sh の「検査パターンは 1 箇所で定義」が実例つきで戒めている
    失敗) を再生産する。"""
    lx = lex(src, rel)
    raw = len(lx.lines)
    generated = is_generated(lx)

    ranges, mod_decls = cfg_test_items(lx)
    test_mods: list[str] = []
    unresolved: list[tuple[int, str]] = []
    for name, line0 in mod_decls:
        hit = ""
        for cand in submodule_candidates(rel, name):
            if (ROOT / cand).is_file():
                hit = cand
                break
        if hit:
            test_mods.append(hit)
        else:
            content = lx.lines[line0].strip() if line0 < raw else f"mod {name};"
            unresolved.append((line0 + 1, content))

    if force_test:
        test_set: set[int] = set(range(raw))
    else:
        test_set = set()
        for a, b in ranges:
            test_set.update(range(a, min(b, raw - 1) + 1))

    ncloc = doc = comment = blank = 0
    for k in range(raw):
        if k in test_set:
            continue
        kind = lx.kind[k]
        if kind == "code":
            ncloc += 1
        elif kind == "doc":
            doc += 1
        elif kind == "comment":
            comment += 1
        else:
            blank += 1

    metrics = FileMetrics(rel=rel, raw=raw, ncloc=ncloc, doc=doc,
                          comment=comment, blank=blank, test=len(test_set))
    total = ncloc + doc + comment + blank + metrics.test
    if total != raw:
        raise LocBudgetError(
            f"保存則違反 {rel}: ncloc {ncloc} + doc {doc} + comment {comment} + "
            f"blank {blank} + test {metrics.test} = {total} != raw {raw}"
        )

    fns: list[FnMetrics] = []
    if not force_test:
        for key, attr_line, decl_line, body_open, body_close in fn_items(lx):
            if decl_line in test_set:
                continue
            fn_ncloc = 0
            max_indent = 0
            deep = 0
            for k in range(body_open, min(body_close, raw - 1) + 1):
                if k in test_set:
                    continue
                if lx.kind[k] == "code":
                    fn_ncloc += 1
                ind = lx.indent[k]
                if ind is None:
                    continue
                if ind > max_indent:
                    max_indent = ind
                if ind >= FN_INDENT_BUDGET:
                    deep += 1
            fns.append(FnMetrics(key=key, rel=rel, line=decl_line + 1,
                                 attr_line=attr_line + 1, body_open=body_open + 1,
                                 ncloc=fn_ncloc, max_indent=max_indent, deep_lines=deep))

    return FileScan(metrics=metrics, fns=fns, lines=lx.lines, generated=generated,
                    force_test=force_test, test_mods=test_mods, unresolved=unresolved)


def _read_source(rel: str) -> str:
    """改行変換をせずに読む。`read_text()` / 既定の text mode は universal newlines なので、
    単独 CR (旧 Mac 改行) まで改行に化けて `wc -l` と食い違う。"""
    with open(ROOT / rel, encoding="utf-8", newline="", errors="replace") as fh:
        return fh.read()


def measure(files: list[str]) -> tuple[list[FileScan], int]:
    """生成物を除いて全ファイルを計測する。戻り値は (走査した FileScan, 除外した生成物の数)。"""
    for rel in files:
        if " " in rel:
            raise LocBudgetError(f"パスに空白が含まれています: {rel!r}。"
                                 "arch_lint.sh がパラメータ展開で分解できません。")
    scans: list[FileScan] = []
    generated = 0
    sources: dict[str, str] = {}
    for rel in files:
        try:
            src = _read_source(rel)
        except OSError as exc:
            raise LocBudgetError(f"{rel} を読めません: {exc}") from exc
        sources[rel] = src
        scan = measure_source(rel, src, force_test=is_integration_test(rel))
        if scan.generated:
            generated += 1
            continue
        scans.append(scan)

    if len(scans) < MIN_SCANNED_FILES:
        raise LocBudgetError(
            f"走査できた .rs が {len(scans)} 件しかありません (下限 {MIN_SCANNED_FILES})。"
            "走査そのものが壊れている可能性が高いので、緑にはしません。"
        )

    # `#[cfg(test)] mod X;` が指すファイルは丸ごとテスト扱い (1 段で足りる)。
    forced = {rel for s in scans for rel in s.test_mods}
    if forced:
        by_rel = {s.rel: idx for idx, s in enumerate(scans)}
        for rel in forced:
            idx = by_rel.get(rel)
            if idx is None:
                continue
            scans[idx] = measure_source(rel, sources[rel], force_test=True)

    return scans, generated


def load_repo(files: list[str] | None = None) -> tuple[list[FileScan], int]:
    return measure(scan_files() if files is None else files)


