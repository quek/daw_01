def emit_check(scans: list[FileScan], generated: int = 0) -> list[str]:
    """違反 1 件 1 行。**print せずに行を返す** — `--self-test` が同じ関数を呼んで
    出力そのものを assert できるようにするため。

    budget 形式 (FILE-BUDGET / FN-BUDGET / FN-NESTING):
        CHECK <キー> <計測値(/区切りの整数ベクトル)> <人間向け…>
    grep 形式 (UNRESOLVED-MOD / KEY-COLLISION):
        CHECK <path>:<line>:<content>
    """
    out: list[str] = []

    files = [s for s in scans
             if s.metrics.ncloc > FILE_NCLOC_BUDGET
             and not _has_allow(s.lines, 0, len(s.lines), ALLOW_MARKER + "file-budget")]
    for s in sorted(files, key=lambda s: (-s.metrics.ncloc, s.rel)):
        m = s.metrics
        out.append(f"FILE-BUDGET {m.rel} {m.ncloc} ncloc>{FILE_NCLOC_BUDGET} "
                   f"(raw {m.raw} / doc {m.doc} / comment {m.comment} / test {m.test})")

    # 行内マーカーの探索範囲は **その関数の attr_line から body_open まで**。
    # 宣言行から後方走査して属性を探す実装にしないこと — doc comment をどこまで遡るかが
    # 曖昧になり、上にある無関係な関数のマーカーを拾い得る。範囲は fn_items() が決めた
    # 1 か所だけが権威。
    over_len: list[FnMetrics] = []
    over_nest: list[FnMetrics] = []
    for s in scans:
        for fn in s.fns:
            lo, hi = fn.attr_line - 1, fn.body_open - 1
            if fn.ncloc > FN_NCLOC_BUDGET and not _has_allow(
                    s.lines, lo, hi, ALLOW_MARKER + "fn-budget"):
                over_len.append(fn)
            if fn.max_indent > FN_INDENT_BUDGET and not _has_allow(
                    s.lines, lo, hi, ALLOW_MARKER + "fn-nesting"):
                over_nest.append(fn)
    for fn in sorted(over_len, key=lambda f: (-f.ncloc, f.key)):
        out.append(f"FN-BUDGET {fn.key} {fn.ncloc} ncloc>{FN_NCLOC_BUDGET} "
                   f"@{fn.rel}:{fn.line}")
    for fn in sorted(over_nest, key=lambda f: (-f.max_indent, -f.deep_lines, f.key)):
        out.append(f"FN-NESTING {fn.key} {fn.max_indent}/{fn.deep_lines} "
                   f"indent>{FN_INDENT_BUDGET} @{fn.rel}:{fn.line}")

    n_unresolved = 0
    for s in sorted(scans, key=lambda s: s.rel):
        for line, content in s.unresolved:
            out.append(f"UNRESOLVED-MOD {s.rel}:{line}:{content}")
            n_unresolved += 1

    seen: dict[str, FnMetrics] = {}
    collisions: list[str] = []
    for s in scans:
        for fn in s.fns:
            if " " in fn.key:
                raise LocBudgetError(f"関数キーに空白が含まれています: {fn.key!r}")
            if fn.key in seen:
                collisions.append(f"KEY-COLLISION {fn.rel}:{fn.line}:key collision: {fn.key}")
            else:
                seen[fn.key] = fn
    out.extend(sorted(collisions))

    n_test = sum(1 for s in scans if s.force_test)
    out.append(f"LOC-BUDGET-OK {len(scans)} files / {n_test} test / {generated} generated "
               f"/ {len(collisions)} key-collision / {n_unresolved} unresolved-mod")
    return out


def report(scans: list[FileScan], generated: int) -> int:
    n_test = sum(1 for s in scans if s.force_test)
    all_fns = [fn for s in scans for fn in s.fns]
    keys: dict[str, int] = {}
    for fn in all_fns:
        keys[fn.key] = keys.get(fn.key, 0) + 1
    n_collision = sum(v - 1 for v in keys.values() if v > 1)
    n_unresolved = sum(len(s.unresolved) for s in scans)

    print(f"loc-budget: {len(scans)} ファイル (テスト扱い {n_test} / 生成物 {generated} 除外 "
          f"/ キー衝突 {n_collision} / 未解決 mod {n_unresolved})")
    print(f"  budget: ファイル {FILE_NCLOC_BUDGET:,} 実コード行 / "
          f"関数 {FN_NCLOC_BUDGET:,} 実コード行 / インデント {FN_INDENT_BUDGET} 段")

    print("\n--- ファイル 実コード行 上位 20 ---")
    print(" ncloc    raw    doc   comment  blank   test  path")
    for s in sorted(scans, key=lambda s: -s.metrics.ncloc)[:20]:
        m = s.metrics
        print(f"{m.ncloc:6d} {m.raw:6d} {m.doc:6d} {m.comment:9d} {m.blank:6d} "
              f"{m.test:6d}  {m.rel}")

    print("\n--- 関数 実コード行 上位 20 ---")
    print(" ncloc  indent  path:line  key")
    for fn in sorted(all_fns, key=lambda f: -f.ncloc)[:20]:
        print(f"{fn.ncloc:6d} {fn.max_indent:7d}  {fn.rel}:{fn.line}  {fn.key}")

    print("\n--- 関数 最大インデント 上位 20 ---")
    print(" indent  >=6行  ncloc  path:line  key")
    for fn in sorted(all_fns, key=lambda f: (-f.max_indent, -f.deep_lines))[:20]:
        print(f"{fn.max_indent:7d} {fn.deep_lines:6d} {fn.ncloc:6d}  "
              f"{fn.rel}:{fn.line}  {fn.key}")
    return 0


# ---------------------------------------------------------------- --filter-comments


def filter_comments(rows: Iterable[str], read=_read_source) -> Iterator[str]:
    """`path:line:content` の行を読み、その行が doc / comment に分類されるなら落とす。

    **読めない path / 範囲外の line は落とさずに残す** — 迷ったら違反を表に出す側に倒す。
    黙って捨てると false negative になる。`path:line:content` の形をしていない行は
    そのまま素通しする (呼び出し側の出力を壊さない)。

    `read` を差し替えられるようにしてあるのは **self-test がこの関数そのものを通せる
    ようにするため**。lex() の行分類だけを別に assert すると、フィルタの落とす / 残すの
    向きが反転しても canary が緑のままになる (= check 1/2/3/5/12 の違反が全部消えても
    誰も気付けない)。"""
    cache: dict[str, Lexed | None] = {}
    for row in rows:
        row = row.rstrip("\n").rstrip("\r")
        parts = row.split(":", 2)
        if len(parts) < 3 or not parts[1].isdigit():
            yield row
            continue
        path, lineno_s, _content = parts
        if path not in cache:
            try:
                cache[path] = lex(read(path), path)
            except OSError:
                cache[path] = None
                print(f"loc-budget: [警告] {path} を読めないので落とさず残します", file=sys.stderr)
        lx = cache[path]
        if lx is None:
            yield row
            continue
        idx = int(lineno_s) - 1
        if idx < 0 or idx >= len(lx.kind):
            print(f"loc-budget: [警告] {path}:{lineno_s} は範囲外なので落とさず残します",
                  file=sys.stderr)
            yield row
            continue
        if lx.kind[idx] in ("doc", "comment"):
            continue
        yield row


# ---------------------------------------------------------------- --self-test


def _fixture(rel: str, src: str, force_test: bool = False) -> FileScan:
    return measure_source(rel, src, force_test=force_test)


def _lines_of(scan: FileScan, prefix: str) -> list[str]:
    return [ln for ln in emit_check([scan]) if ln.startswith(prefix + " ")]


def self_test() -> int:
    """合成フィクスチャだけで判定器を検証する (リポジトリの内容に依存させない —
    依存させると「repo が変わった」のか「判定器が壊れた」のか区別できなくなる)。

    フィクスチャは必ず `measure_source()` → `emit_check()` を通す。別実装で assert すると
    canary が検査対象と別物を試すことになる。"""
    fails: list[str] = []
    n_fixture = 0
    n_conserve = 0

    def check(cond: bool, msg: str) -> None:
        nonlocal n_fixture
        n_fixture += 1
        if not cond:
            fails.append(msg)

    def scan(rel: str, src: str, force_test: bool = False) -> FileScan:
        nonlocal n_conserve
        s = _fixture(rel, src, force_test)   # 保存則は measure_source 内で assert 済み
        n_conserve += 1
        return s

    # ---- (A) 分類器 ----------------------------------------------------------
    # 1. raw string 中の行頭 `//` はコメントではない。`{` も解釈しない。
    s = scan("selftest/a1.rs", 'fn f() {\nlet s = r#"\n// これはコメントではない {\n"#;\n}\n')
    check(s.metrics.comment == 0, "A1: raw string 中の // が comment に数えられた")
    check(s.metrics.ncloc == 5, f"A1: ncloc が 5 でない ({s.metrics.ncloc})")

    # 2. 文字列中の対応しない `{` で cfg(test) 範囲が desync しない (project.rs:1815 型)
    src2 = ('#[cfg(test)]\nmod t {\n    fn a() { let s = "not valid json {"; }\n}\n'
            'pub fn production() {\n    let x = 1;\n}\n')
    s = scan("selftest/a2.rs", src2)
    check(s.metrics.test == 4, f"A2: test 範囲が 4 行でない ({s.metrics.test})")
    check(s.metrics.ncloc == 3, f"A2: production が 3 行でない ({s.metrics.ncloc})")

    # 3. ネストしたブロックコメント
    s = scan("selftest/a3.rs", "/* /* ネスト */ まだコメント */\nlet x = 1;\n")
    check(s.metrics.comment == 1 and s.metrics.ncloc == 1, "A3: ネストコメントの分類")

    # 4. mod でなくても cfg(test) なら test 扱い (compile.rs:900 型)
    s = scan("selftest/a4.rs", "#[cfg(test)]\npub(crate) fn f() {\n    let a = 1;\n}\nfn g() {}\n")
    check(s.metrics.test == 4, f"A4: cfg(test) fn が test 扱いでない ({s.metrics.test})")

    # 5. `#[cfg(test)] mod tests;` の宣言を拾う
    lx = lex("#[cfg(test)]\nmod tests;\n", "selftest/a5.rs")
    _r, mods = cfg_test_items(lx)
    check(mods == [("tests", 1)], f"A5: mod 宣言を拾えていない ({mods})")

    # 6. ライフタイムと char を取り違えない。`'}'` で深さが動かない。
    s = scan("selftest/a6.rs", "fn f<'a>(x: &'a str) -> char { '}' }\nfn g() {}\n")
    fns6 = {f.key for f in s.fns}
    check(fns6 == {"selftest/a6.rs::f", "selftest/a6.rs::g"}, f"A6: 関数が拾えていない ({fns6})")

    # 6b. `'\\'` (エスケープされたバックスラッシュ) が閉じ `'` を食い潰さない。
    #     食い潰すと次の `'` まで literal が伸び、そこから先の字句解析が丸ごとずれる
    #     (実装中に ui/crates/ui/src/shortcut.rs:500 で発火した。関数 1 本が消えていた)。
    #     **後続行の分類まで assert する** — 関数が 2 本見つかるだけの assert では、
    #     literal の伸び方によっては偶然通ってしまう。
    s = scan("selftest/a6b.rs",
             "fn f() {\n    let t = [(\"\\\\\", '\\\\'), (\"'\", '\\'')];\n}\n"
             "// ここはコメント\nfn g() {}\n")
    check({f.key for f in s.fns} == {"selftest/a6b.rs::f", "selftest/a6b.rs::g"},
          f"A6b: '\\\\' の後で字句解析がずれた ({[f.key for f in s.fns]})")
    check(s.metrics.comment == 1 and s.metrics.ncloc == 4,
          f"A6b: 後続行の分類が壊れた (comment {s.metrics.comment} / ncloc {s.metrics.ncloc})")

    # 7. `#[cfg(feature = "test")]` を test 扱いにしない
    s = scan("selftest/a7.rs", '#[cfg(feature = "test")]\nfn f() {}\n')
    check(s.metrics.test == 0, f"A7: feature=\"test\" を test 扱いにした ({s.metrics.test})")

    # 8. 関数ポインタ型 / 本体無しの trait 宣言は関数 item ではない
    s = scan("selftest/a8.rs", "type F = fn(u32) -> u32;\ntrait T { fn g(); }\n")
    check(s.fns == [], f"A8: 関数でないものを拾った ({[f.key for f in s.fns]})")

    # 9. `////` は comment、`///` `//!` `/** */` は doc
    s = scan("selftest/a9.rs", "//// 4 本\n/// doc\n//! inner\n/** doc */\n")
    check(s.metrics.comment == 1 and s.metrics.doc == 3,
          f"A9: doc/comment の分類 (doc {s.metrics.doc} / comment {s.metrics.comment})")

    # 10. b"" / c"" / br#""# が文字列として閉じる
    s = scan("selftest/a10.rs", 'fn f() {\n    let a = b"x";\n    let b = c"y";\n'
                                '    let c = br#"z"#;\n}\n')
    check(s.metrics.ncloc == 5 and s.metrics.comment == 0, "A10: byte/C/raw 文字列の扱い")

    # 11. 同名 fn を 2 つの impl に持つ入力 → key が分かれる
    s = scan("selftest/a11.rs", "impl A { fn new() {} }\nimpl B { fn new() {} }\n")
    check({f.key for f in s.fns} == {"selftest/a11.rs::A::new", "selftest/a11.rs::B::new"},
          f"A11: impl のスコープ ({[f.key for f in s.fns]})")

    # 12. 深い入れ子 + 内部の raw string (字下げされた WGSL) が max_indent を汚さない
    deep = "fn f() {\n"
    for d in range(1, 8):
        deep += " " * (4 * d) + f"let v{d} = {d};\n"
    deep += '    let s = r#"\n' + " " * 60 + "// wgsl\n" + '"#;\n}\n'
    s = scan("selftest/a12.rs", deep)
    check(s.fns and s.fns[0].max_indent == 7,
          f"A12: max_indent が raw string に汚染された ({s.fns[0].max_indent if s.fns else None})")

    # 13. `arch-lint: allow-fn-nesting` を付けた深い関数は違反にしない
    allowed = "fn deep() { // arch-lint: allow-fn-nesting\n"
    for d in range(1, 9):
        allowed += " " * (4 * d) + f"let v{d} = {d};\n"
    allowed += "}\n"
    check(_lines_of(scan("selftest/a13.rs", allowed), "FN-NESTING") == [],
          "A13: allow-fn-nesting が効いていない")

    # 14. `#[cfg(test)] use foo::{a, b};` は `}` の直後の `;` まで
    s = scan("selftest/a14.rs", "#[cfg(test)]\nuse foo::{a, b};\nfn prod() {\n    let x = 1;\n}\n")
    check(s.metrics.test == 2 and s.metrics.ncloc == 3,
          f"A14: use の範囲 (test {s.metrics.test} / ncloc {s.metrics.ncloc})")

    # 15. `->` と `>>` で本体の開きを取り違えない
    s = scan("selftest/a15.rs",
             "fn f() -> bool {\n    true\n}\nfn g<T: Into<String>>(x: T) {\n    let _ = x;\n}\n")
    check({f.key for f in s.fns} == {"selftest/a15.rs::f", "selftest/a15.rs::g"},
          f"A15: 本体の開きを取り違えた ({[(f.key, f.ncloc) for f in s.fns]})")
    check(all(f.ncloc == 3 for f in s.fns), f"A15: ncloc ({[f.ncloc for f in s.fns]})")

    # 16. impl の外の自由関数はスコープ空
    s = scan("selftest/a16.rs", "pub fn draw() {}\n")
    check([f.key for f in s.fns] == ["selftest/a16.rs::draw"], "A16: 自由関数のキー")

    # 17. generics 付き impl は generics を飛ばした直後の識別子が型名 (text_input.rs:181 型)
    s = scan("selftest/a17.rs", "impl<'a, M: ?Sized + 'static> Ui<'a, M> {\n    pub fn f() {}\n}\n")
    check([f.key for f in s.fns] == ["selftest/a17.rs::Ui::f"],
          f"A17: generics 付き impl のキー ({[f.key for f in s.fns]})")

    # 18. 同一型への複数 trait impl (midi_import.rs:120,128 型)
    s = scan("selftest/a18.rs",
             "impl From<std::io::Error> for E { fn from() {} }\n"
             "impl From<midly::Error> for E { fn from() {} }\n")
    check({f.key for f in s.fns} == {"selftest/a18.rs::E[From<std::io::Error>]::from",
                                     "selftest/a18.rs::E[From<midly::Error>]::from"},
          f"A18: trait impl のキー ({[f.key for f in s.fns]})")
    check(_lines_of(s, "KEY-COLLISION") == [], "A18: trait 修飾で衝突が消えていない")

    # 19. cfg 対の mod (shmem.rs:32,170 型)
    s = scan("selftest/a19.rs",
             "#[cfg(windows)]\nmod imp { impl T { fn f() {} } }\n"
             "#[cfg(unix)]\nmod imp { impl T { fn f() {} } }\n")
    check({f.key for f in s.fns} == {"selftest/a19.rs::imp[cfg(windows)]::T::f",
                                     "selftest/a19.rs::imp[cfg(unix)]::T::f"},
          f"A19: cfg 付き mod のキー ({[f.key for f in s.fns]})")

    # 20. cfg(debug_assertions) 対 — どちらも production コード (main.rs:831,848 型)
    s = scan("selftest/a20.rs",
             "#[cfg(debug_assertions)]\nfn g() {}\n#[cfg(not(debug_assertions))]\nfn g() {}\n")
    check({f.key for f in s.fns} == {"selftest/a20.rs::g[cfg(debug_assertions)]",
                                     "selftest/a20.rs::g[cfg(not(debug_assertions))]"},
          f"A20: cfg 付き fn のキー ({[f.key for f in s.fns]})")
    check(s.metrics.test == 0, f"A20: debug_assertions を test 扱いにした ({s.metrics.test})")

    # 21. cfg 以外の属性はキーに入れない
    s = scan("selftest/a21.rs", "#[allow(clippy::too_many_lines)]\nfn h() {}\n")
    check([f.key for f in s.fns] == ["selftest/a21.rs::h"],
          f"A21: cfg 以外の属性がキーに入った ({[f.key for f in s.fns]})")

    # 22. 同じキーの関数が 2 本 → KEY-COLLISION を 1 本出す (#2 の連番で黙らせない)
    s = scan("selftest/a22.rs", "impl Foo { fn new() {} }\nimpl Foo { fn new() {} }\n")
    coll = _lines_of(s, "KEY-COLLISION")
    check(len(coll) == 1 and coll[0].endswith("key collision: selftest/a22.rs::Foo::new"),
          f"A22: KEY-COLLISION ({coll})")

    # 23. CRLF / 末尾改行なしの raw
    s = scan("selftest/a23.rs", "fn f() {\r\n    let x = 1;\r\n}\r\n")
    check(s.metrics.raw == 3 and s.metrics.ncloc == 3, f"A23: CRLF の raw ({s.metrics.raw})")
    s = scan("selftest/a23b.rs", "fn f() {}\nlet x = 1;")
    check(s.metrics.raw == 2, f"A23: 末尾改行なしの raw ({s.metrics.raw})")

    # 24. 先頭が生成マーカーのコメント → 生成物
    s = scan("selftest/a24.rs", "/* automatically generated by rust-bindgen 0.71.1 */\nfn f() {}\n")
    check(s.generated, "A24: 生成物として判定できていない")

    # 25. 先頭コメントが無く、コード中の文字列に `// @generated` (ara-sys/build.rs:47 型)
    s = scan("selftest/a25.rs",
             'fn main() {\n    b.raw_line("// @generated by cargo — do not edit by hand.");\n}\n')
    check(not s.generated, "A25: 文字列中の @generated を生成物と誤判定した")
    # 25b. **先頭コメントブロックの「外」にある本物のコメント**は生成マーカーにしない。
    #      これが無いと「ファイル中のどこかのコメントを見る」実装でも A25 が通ってしまい、
    #      §1.4 の「先頭の連続コメント/空行ブロックだけを見る」規則が pin されない。
    s = scan("selftest/a25b.rs",
             "fn main() {}\n// automatically generated by something\nfn other() {}\n")
    check(not s.generated, "A25b: 先頭ブロックの外のコメントを生成マーカーに数えた")
    # 25c. 先頭が空行 + 行コメントでもマーカーなら生成物 (先頭ブロックの定義の確認)
    s = scan("selftest/a25c.rs", "\n// @generated\n\nfn main() {}\n")
    check(s.generated, "A25c: 先頭ブロック内のマーカーを見落とした")

    # 26a. **`#[cfg(not(test))]` を test 扱いにしない。** `not(test)` は
    #      「テストビルド以外でだけコンパイルされる」= production コードなので、
    #      test 扱いにすると production が丸ごと budget から消えて緑になる。
    prod = "".join(f"    let v{k} = {k};\n" for k in range(20))
    s = scan("selftest/a26a.rs", "#[cfg(not(test))]\npub mod win {\n" + prod + "}\n")
    check(s.metrics.test == 0 and s.metrics.ncloc == 23,
          f"A26a: cfg(not(test)) を test 扱いにした (test {s.metrics.test} / ncloc {s.metrics.ncloc})")
    check(not _is_cfg_test("cfg(all(not(test),windows))"),
          "A26a: cfg(all(not(test),…)) を test 扱いにした")
    check(_is_cfg_test("cfg(all(test,not(windows)))"),
          "A26a: cfg(all(test,not(…))) を test 扱いにできていない")
    check(_is_cfg_test("cfg(any(test,debug_assertions))"),
          "A26a: cfg(any(test,…)) を test 扱いにできていない")

    # 26b. **item でないもの (enum variant / struct field) に付いた `#[cfg(test)]` で
    #      範囲が暴走しない。** 暴走するとファイル末尾までテスト扱いになり、
    #      そこから先の違反が全部消える (このリポジトリが最も警戒する false green)。
    s = scan("selftest/a26b.rs",
             "enum E {\n    A,\n    #[cfg(test)]\n    B,\n    C,\n}\n"
             "pub fn production() {\n    let x = 1;\n}\n")
    check(s.metrics.test == 2 and s.metrics.ncloc == 7,
          f"A26b: variant の cfg(test) 範囲が暴走した (test {s.metrics.test} / ncloc {s.metrics.ncloc})")
    check([f.key for f in s.fns] == ["selftest/a26b.rs::production"],
          f"A26b: 後続の production 関数が消えた ({[f.key for f in s.fns]})")
    # 26c. 囲みブロックの終わりでも打ち切る (`,` が無い最後の field)
    s = scan("selftest/a26c.rs",
             "struct S {\n    #[cfg(test)]\n    a: u32\n}\npub fn production() {\n    let x = 1;\n}\n")
    check([f.key for f in s.fns] == ["selftest/a26c.rs::production"],
          f"A26c: field の cfg(test) 範囲が暴走した ({[f.key for f in s.fns]})")
    # 26d. generics の `,` で item を切らない (`fn f<A, B>()`)
    s = scan("selftest/a26d.rs",
             "#[cfg(test)]\nfn t<A, B>() {\n    let x = 1;\n}\npub fn production() {}\n")
    check(s.metrics.test == 4 and [f.key for f in s.fns] == ["selftest/a26d.rs::production"],
          f"A26d: generics の , で範囲を切った (test {s.metrics.test})")

    # 26e. **属性の塊の先頭行から範囲が始まる** (`#[allow]` が `#[cfg(test)]` の上にある形)
    s = scan("selftest/a26e.rs",
             "#[allow(dead_code)]\n#[cfg(test)]\nfn t() {\n    let x = 1;\n}\nfn prod() {}\n")
    check(s.metrics.test == 5 and s.metrics.ncloc == 1,
          f"A26e: 塊の先頭属性行が範囲に入っていない (test {s.metrics.test} / ncloc {s.metrics.ncloc})")

    # 26f. **型位置の `impl Trait` は scope を作らない。** 作ると入れ子の fn のキーが
    #      `<rel>::Foo::inner` に化ける (= baseline のキーが黙って別物になる)。
    s = scan("selftest/a26f.rs",
             "pub fn outer(x: impl Foo) -> impl Bar {\n    fn inner() {}\n    x\n}\n")
    check({f.key for f in s.fns} == {"selftest/a26f.rs::outer", "selftest/a26f.rs::inner"},
          f"A26f: 型位置の impl が偽スコープを作った ({[f.key for f in s.fns]})")

    # 26g. **内部属性 (`#![…]`) を次の item に積まない。**
    s = scan("selftest/a26g.rs", "#![cfg(feature)]\npub fn f() {}\n")
    check([f.key for f in s.fns] == ["selftest/a26g.rs::f"],
          f"A26g: 内部属性がキーへ漏れた ({[f.key for f in s.fns]})")

    # 26h. **force_test / 統合テスト判定**。ここが壊れると 164 件の違反が全部消えて
    #      arch-lint は「OK」で exit 0 になる。
    s = scan("selftest/a26h.rs", "pub fn f() {\n    let x = 1;\n}\n", force_test=True)
    check(s.metrics.ncloc == 0 and s.metrics.test == s.metrics.raw and s.fns == [],
          f"A26h: force_test が効いていない ({s.metrics})")
    check(is_integration_test("tests/zz_selftest.rs"),
          "A26h: tests/ 直下 (親に Cargo.toml) を統合テストと判定できない")
    check(not is_integration_test("zz_no_such_crate/tests/x.rs"),
          "A26h: 親に Cargo.toml が無い tests/ を統合テストと判定した")
    check(not is_integration_test("common/src/model/tests.rs"),
          "A26h: tests.rs という名前だけで統合テスト扱いにした")

    # ---- (B) 肯定側 canary — emit_check が実際に違反を出すこと ------------------
    # 26/27. FILE-BUDGET の境界
    over = "".join(f"const A{k}: u32 = {k};\n" for k in range(FILE_NCLOC_BUDGET + 1))
    hits = _lines_of(scan("selftest/b26.rs", over), "FILE-BUDGET")
    check(len(hits) == 1 and hits[0].split()[2] == str(FILE_NCLOC_BUDGET + 1),
          f"B26: FILE-BUDGET が 1001 行で出ない ({hits})")
    exact = "".join(f"const A{k}: u32 = {k};\n" for k in range(FILE_NCLOC_BUDGET))
    check(_lines_of(scan("selftest/b27.rs", exact), "FILE-BUDGET") == [],
          "B27: FILE-BUDGET が境界 1000 で出てしまう")

    # 28/29. FN-BUDGET の境界
    def fn_of(ncloc: int) -> str:
        body = "".join(f"    let v{k} = {k};\n" for k in range(ncloc - 2))
        return f"fn f() {{\n{body}}}\n"
    hits = _lines_of(scan("selftest/b28.rs", fn_of(FN_NCLOC_BUDGET + 1)), "FN-BUDGET")
    check(len(hits) == 1 and hits[0].split()[2] == str(FN_NCLOC_BUDGET + 1),
          f"B28: FN-BUDGET が 301 行で出ない ({hits})")
    check(_lines_of(scan("selftest/b29.rs", fn_of(FN_NCLOC_BUDGET)), "FN-BUDGET") == [],
          "B29: FN-BUDGET が境界 300 で出てしまう")

    # 30/31. FN-NESTING の境界
    def nest_of(depth: int) -> str:
        body = "".join(" " * (4 * d) + f"let v{d} = {d};\n" for d in range(1, depth + 1))
        return f"fn f() {{\n{body}}}\n"
    hits = _lines_of(scan("selftest/b30.rs", nest_of(FN_INDENT_BUDGET + 1)), "FN-NESTING")
    check(len(hits) == 1 and hits[0].split()[2] == f"{FN_INDENT_BUDGET + 1}/2",
          f"B30: FN-NESTING の計測値 ({hits})")
    check(_lines_of(scan("selftest/b31.rs", nest_of(FN_INDENT_BUDGET)), "FN-NESTING") == [],
          "B31: FN-NESTING が境界 6 段で出てしまう")

    # 32. 解決できない `#[cfg(test)] mod X;`
    hits = _lines_of(scan("selftest/b32.rs", "#[cfg(test)]\nmod nonexistent_zzz;\n"),
                     "UNRESOLVED-MOD")
    check(len(hits) == 1, f"B32: UNRESOLVED-MOD ({hits})")

    # 33. 何も違反しない入力 → LOC-BUDGET-OK の 1 行だけ
    out33 = emit_check([scan("selftest/b33.rs", "fn f() {\n    let x = 1;\n}\n")])
    check(len(out33) == 1 and out33[0].startswith("LOC-BUDGET-OK "),
          f"B33: 完走マーカーだけにならない ({out33})")

    # 34. 属性行に付けた allow-fn-budget が効く (§3.8 の範囲が attr_line から始まる証明)
    marked = "#[inline] // arch-lint: allow-fn-budget\n" + fn_of(FN_NCLOC_BUDGET + 1)
    check(_lines_of(scan("selftest/b34.rs", marked), "FN-BUDGET") == [],
          "B34: 属性行の allow-fn-budget が効いていない")

    # ---- (C) --filter-comments -------------------------------------------------
    # **フィルタ本体 (filter_comments) を通す。** lex の分類だけを assert すると、
    # 落とす / 残すの向きが反転しても canary が緑のままになり、check 1/2/3/5/12 の
    # 違反が全部消えても誰も気付けない。合成ファイルは read の差し替えで与える。
    FIXTURE_FILES = {
        "selftest/c_raw.rs": 'fn f() {\n    let s = r#"\n// pool: HashMap<(u32, u32), Bogus>\n"#;\n}\n',
        "selftest/c_line.rs": "// pool: HashMap<(u32, u32), Bogus>\nlet x = 1;\n",
        "selftest/c_block.rs": "/*\npool: HashMap<(u32, u32), Bogus>\n*/\nlet x = 1;\n",
        "selftest/c_trail.rs": "foo(); // x\n",
    }

    def fake_read(path: str) -> str:
        if path in FIXTURE_FILES:
            return FIXTURE_FILES[path]
        raise OSError(f"selftest: {path} は存在しません")

    def filt(rows: list[str]) -> list[str]:
        return list(filter_comments(rows, read=fake_read))

    # 35. raw string 中の行頭 `//` を指す行は **残る** (旧 strip_comments はここを落としていた)
    row35 = "selftest/c_raw.rs:3:// pool: HashMap<(u32, u32), Bogus>"
    check(filt([row35]) == [row35], "C35: raw string 中の行頭 // を落としてしまった")
    # 36. 本物の行頭コメント行を指す行は落ちる
    check(filt(["selftest/c_line.rs:1:// pool: HashMap<(u32, u32), Bogus>"]) == [],
          "C36: 本物の行頭コメント行を落とせない")
    # 37. `/* … */` の中の行を指す行は落ちる (旧実装は落とせていなかった)
    check(filt(["selftest/c_block.rs:2:pool: HashMap<(u32, u32), Bogus>"]) == [],
          "C37: ブロックコメント内の行を落とせない")
    # 38. 末尾コメント付きの実コード行を指す行は残る
    row38 = "selftest/c_trail.rs:1:foo(); // x"
    check(filt([row38]) == [row38], "C38: 末尾コメント付きの実コード行を落としてしまった")
    # 38b. 範囲外の行番号は落とさずに残す
    row38b = "selftest/c_trail.rs:99:foo();"
    check(filt([row38b]) == [row38b], "C38b: 範囲外の行番号を落としてしまった")
    # 39. 存在しない path は残す (read が OSError を投げる経路)
    row39 = "selftest/does_not_exist.rs:1:    pool: HashMap<(u32, u32), Bogus>,"
    check(filt([row39]) == [row39], "C39: 読めない path の行を落としてしまった")
    # 40. path:line:content の形をしていない行はそのまま素通し
    check(filt(["arch-lint: [NOTE] 何か", "not a row"]) == ["arch-lint: [NOTE] 何か", "not a row"],
          "C40: 形の違う行を素通しできていない")

    # ---- (D) 走査の下限 --------------------------------------------------------
    # 41. 走査が下限を割ったら緑にせず落ちる
    try:
        load_repo(files=[])
        check(False, "D41: 走査 0 件でも例外にならない")
    except LocBudgetError:
        check(True, "")
    # 42. git が起動できない / 非ゼロ終了なら空リストへ縮退しない
    try:
        scan_files(["git-does-not-exist-zzz", "ls-files"])
        check(False, "D42: git 不在で例外にならない")
    except LocBudgetError:
        check(True, "")
    try:
        scan_files(["git", "ls-files", "--this-option-does-not-exist-zzz"])
        check(False, "D42: git の非ゼロ終了で例外にならない")
    except LocBudgetError:
        check(True, "")

    if fails:
        print("loc-budget: self-test FAILED", file=sys.stderr)
        for f in fails:
            print(f"  - {f}", file=sys.stderr)
        return 1
    print(f"loc-budget: self-test ok (フィクスチャ {n_fixture} 件 / 保存則 {n_conserve} 件)")
    return 0


# ---------------------------------------------------------------- main


def main() -> int:
    ap = argparse.ArgumentParser(description="サイズ budget (不変条件 9) の測定器",
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="違反を stdout へ (arch_lint.sh が読む)")
    mode.add_argument("--report", action="store_true", help="上位ファイル / 関数の一覧")
    mode.add_argument("--self-test", action="store_true", help="判定器そのものの自己検査")
    mode.add_argument("--filter-comments", action="store_true",
                      help="stdin の path:line:content からコメント行を落とす")
    args = ap.parse_args()

    if args.self_test:
        return self_test()

    if args.filter_comments:
        try:
            sys.stdin.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):  # pragma: no cover
            pass
        for row in filter_comments(sys.stdin):
            print(row)
        return 0

    try:
        scans, generated = load_repo()
    except LocBudgetError as exc:
        print(f"loc-budget: [SELF-BROKEN] {exc}", file=sys.stderr)
        return 2

    try:
        if args.report:
            return report(scans, generated)
        for line in emit_check(scans, generated):
            print(line)
    except LocBudgetError as exc:
        print(f"loc-budget: [SELF-BROKEN] {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
